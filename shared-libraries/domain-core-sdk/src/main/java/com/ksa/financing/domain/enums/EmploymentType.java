package com.ksa.financing.domain.enums;

/**
 * Employment type classification for Saudi Arabia.
 *
 * @author KSA Financing Platform
 * @since 1.0.0
 */
public enum EmploymentType {
    /** Government sector employee */
    GOVERNMENT,

    /** Semi-government entity (e.g., Aramco, SABIC) */
    SEMI_GOVERNMENT,

    /** Private sector employee */
    PRIVATE,

    /** Self-employed/freelancer */
    SELF_EMPLOYED,

    /** Business owner */
    BUSINESS_OWNER,

    /** Retired with pension */
    RETIRED,

    /** Not currently employed */
    UNEMPLOYED
}
